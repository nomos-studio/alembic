(ns examples.gsot.22-ramp-div-musical
  "GSOT pp.48-49 — go.ramp.div in musical context: note-value subdivisions.

  'Musically relevant divisions'
  --------------------------------
  The pages apply go.ramp.div (example 21) to a beat ramp generated by
  go.ramp.frombpm (example 12), showing how integer division values map to
  standard Western note-value relationships:

      div=1  → beat ramp unchanged          (quarter note at 4/4)
      div=2  → half-time; one cycle per 2 beats  (half note)
      div=3  → triplet feel; one cycle per 3 beats (dotted quarter, or bar of 3)
      div=4  → one cycle per 4 beats        (whole note / one measure at 4/4)
      div=6  → one cycle per 6 beats        (dotted half in compound meter)
      div=8  → one cycle per 8 beats        (double-whole note / 2 bars)

  The musically relevant divisors are small integers that correspond to
  common note values and metric levels.  Irrational or large values produce
  polyrhythmic relationships; the section focuses on the integer cases that
  align with standard notation.

  Signal flow
  -----------
  This example chains the two utilities shown in the chapter:

      go.ramp.frombpm → beat-ramp → go.ramp.div → divided-ramp

      BPM + beats → measure phasor
                  → * beats → wrap 0 1       beat-ramp  [0,1) per beat
                  → go.ramp.div(N)            divided    [0,1) per N beats

  The measure ramp is also output so that the slow ramp and the driving
  clock are both available as patch outputs.

  go.ramp.div applied to the beat ramp
  --------------------------------------
  In the maxpat on pp.48-49, the beat ramp from go.ramp.frombpm feeds
  directly into go.ramp.div.gendsp.  The division param (integer N) selects
  the note-value level.  The result is a ramp that completes one cycle per
  N beats — suitable as a sequencer advance clock, an envelope trigger
  period, or a loop-length reference.

  Implementation note: counter max
  ----------------------------------
  The counter inside go.ramp.div is capped at 1024 (see example 21).  For
  musically relevant N ≤ 8 at any practical tempo, the cap is never reached
  within a session — the beat count before counter overflow at 1024 triggers
  is 1024/N ≥ 128 measures.

  Emitted Faust DSP
  -----------------
