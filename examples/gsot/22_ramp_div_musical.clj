      n22 = (n21 + fmod((n19 - n21), (n17 - n21)));
      n23 = (n22 + n10);
      n24 = (n23 / n17);

      process = n24, n10, n6;"
  (:require [alembic.patch :refer [defpatch!]]))

(defpatch! ramp-div-musical
  {:params {:bpm   {:range [20.0 300.0] :default 120.0 :unit :bpm}
            :beats {:range [1.0 16.0]   :default 4.0   :unit :beats}
            :div   {:range [1.0 8.0]    :default 2.0}}}
  (let [;; go.ramp.frombpm — measure and beat ramps
        bpm-hz  (div (param :bpm) (const 60.0))
        beats   (floor (param :beats))
        hz      (div bpm-hz beats)
        measure (phasor hz)
        beat    (wrap (mul measure beats) (const 0.0) (const 1.0))
        ;; go.ramp.div — divide the beat ramp by N
        d       (delta beat)
        cmp     (comparator (abs d) (const 0.5))
        trig    (:out cmp)
        n       (floor (param :div))
        cnt     (counter {:max 1024 :dir :up :wrap true} trig (const 0.0))
        count   (wrap (:out cnt) (const 0.0) n)
        divided (div (add count beat) n)]
    (output :divided divided)
    (output :beat    beat)
    (output :measure measure)))
